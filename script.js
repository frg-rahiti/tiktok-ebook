    let currentLanguage = "fr";
    let currentFilter = "all";


    /* =========================
       AFFICHER LES PRODUITS
    ========================= */

    function renderProducts(filter = "all") {

        const grid = document.getElementById("productsGrid");
        grid.innerHTML = "";

        const filtered = filter === "all"
            ? products
            : products.filter(product => product.category === filter);

        const t = translations[currentLanguage];

        filtered.forEach(product => {

            const data = product[currentLanguage];

            let categoryName;
            if (product.category === "prompts") {
                categoryName = t.categoryPrompts;
            } else if (product.category === "creation") {
                categoryName = t.categoryCreation;
            } else {
                categoryName = t.categoryCopywriting;
            }

            const card = document.createElement("div");
            card.className = "product-card";

            card.innerHTML = `
                <span class="product-edition">${product.edition}</span>

                <div class="product-image">
                    <img src="${product.image}" alt="${data.title}" loading="lazy">
                </div>

                <div class="product-content">

                    <span class="product-category">${categoryName}</span>

                    <h3 class="product-title">${data.title}</h3>

                    <p class="product-desc">${data.description}</p>

                    <ul class="product-features">
                        ${data.features.map(feature => `<li>${feature}</li>`).join("")}
                    </ul>

                    <div class="product-price">
                        <span class="price-tag"><span class="currency">€</span>${product.price}</span>
                        <span class="price-note">${t.once}</span>
                    </div>

                    <div class="product-guarantee">${t.guarantee}</div>

                    <a href="${product.link}" class="product-cta">
                        <span>${t.buy}</span><span class="arrow">${t.arrow}</span>
                    </a>

                </div>
            `;

            grid.appendChild(card);
        });
    }


    /* =========================
       COMMENT ÇA MARCHE
    ========================= */

    function renderSteps() {
        const t = translations[currentLanguage];
        const grid = document.getElementById("stepsGrid");
        grid.innerHTML = t.steps.map((step, i) => `
            <div class="step">
                <div class="step-num">0${i + 1}</div>
                <div class="step-title">${step.title}</div>
                <div class="step-desc">${step.desc}</div>
            </div>
        `).join("");
    }


    /* =========================
       TÉMOIGNAGES
    ========================= */

    function renderTestimonials() {
        const t = translations[currentLanguage];
        const grid = document.getElementById("testimonialsGrid");
        grid.innerHTML = t.testimonials.map(item => `
            <div class="testimonial">
                <div class="testimonial-stars">★★★★★</div>
                <div class="testimonial-quote">"${item.quote}"</div>
                <div class="testimonial-author">${item.author}</div>
            </div>
        `).join("");
        document.getElementById("testiNote").textContent = t.testiNote;
    }


    /* =========================
       FAQ
    ========================= */

    function renderFaq() {
        const t = translations[currentLanguage];
        const list = document.getElementById("faqList");
        list.innerHTML = t.faq.map((item, i) => `
            <div class="faq-item" id="faqItem${i}">
                <button class="faq-question" onclick="toggleFaq(${i})">
                    <span>${item.q}</span>
                    <span class="faq-icon">+</span>
                </button>
                <div class="faq-answer"><p>${item.a}</p></div>
            </div>
        `).join("");
    }

    function toggleFaq(i) {
        const item = document.getElementById("faqItem" + i);
        item.classList.toggle("open");
    }


    /* =========================
       CHANGER DE LANGUE
    ========================= */

    function changeLanguage(language, btn) {

        currentLanguage = language;
        const t = translations[language];

        document.documentElement.lang = language;

        document.getElementById("eyebrowLabel").textContent = t.eyebrowLabel;
        document.getElementById("headerDescription").textContent = t.headerDescription;
        document.getElementById("headerCta").querySelector("span").textContent = t.headerCta;
        document.getElementById("topbarCta").textContent = t.topbarCta;
        document.getElementById("trust1").textContent = t.trust1;
        document.getElementById("trust2").textContent = t.trust2;
        document.getElementById("trust3").textContent = t.trust3;
        document.getElementById("heroTitle").textContent = t.heroTitle;
        document.getElementById("heroDescription").textContent = t.heroDescription;
        document.getElementById("filterAll").textContent = t.all;
        document.getElementById("filterPrompts").textContent = t.prompts;
        document.getElementById("filterCreation").textContent = t.creation;
        document.getElementById("filterCopywriting").textContent = t.copywriting;

        document.getElementById("howEyebrow").textContent = t.howEyebrow;
        document.getElementById("howTitle").textContent = t.howTitle;
        document.getElementById("testiEyebrow").textContent = t.testiEyebrow;
        document.getElementById("testiTitle").textContent = t.testiTitle;
        document.getElementById("faqEyebrow").textContent = t.faqEyebrow;
        document.getElementById("faqTitle").textContent = t.faqTitle;

        document.getElementById("footerGuarantee").textContent = t.footerGuarantee;
        document.getElementById("footerQuestion").textContent = t.footerQuestion;
        document.getElementById("footerCopyright").textContent = t.footerCopyright;

        document.querySelectorAll(".language-btn").forEach(button => {
            button.classList.remove("active");
        });
        btn.classList.add("active");

        renderProducts(currentFilter);
        renderSteps();
        renderTestimonials();
        renderFaq();
    }


    /* =========================
       FILTRER LES PRODUITS
    ========================= */

    function filterProducts(category, button) {

        currentFilter = category;

        document.querySelectorAll(".filter-btn").forEach(btn => {
            btn.classList.remove("active");
        });

        button.classList.add("active");

        renderProducts(category);
    }


    /* =========================
       INITIALISATION
    ========================= */

    renderProducts();
    renderSteps();
    renderTestimonials();
    renderFaq();
